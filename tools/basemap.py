# -*- coding: utf-8 -*-
"""기본 폰트 256글리프 → 유니코드 매핑표.

출처 = `COMMON.DAT +0x1068A` (JP) / `+0x10EAA` (US, 바이트 동일) 를 16열 시트로
렌더해 읽은 것. 실측 보조 사실:
  * 빈 글리프는 index 1 하나뿐 (= 공백)
  * index 0 과 255 가 같은 비트맵 (= ※)
한자 30여 자는 이 표에 그대로 들어 있고, 그 밖의 한자는 장면별 `.FNT`(index 256~)다.
"""

# 16글자씩 16행. '?' 는 아직 확정 못 읽은 자리(현재 없음).
ROWS = [
    "※　0123456789あいうえ",
    "おかきくけこさしすせそたちつてと",
    "なにぬねのはひふへほまみむめもや",
    "ゆよらりるれろわをん…()『』！",
    "？ー＋。「」、・ヲァィゥェォャュ",
    "ョッーアイウエオカキクケコサシス",
    "セソタチツテトナニヌネノハヒフヘ",
    "ホマミムメモヤユヨラリルレロワン",
    "ヴ×／ガギグゲゴザジズゼゾダヂヅ",
    # ★탁점(゛)과 반탁점(゜)의 순서에 주의 — 12×11 픽셀에서는 둘이 거의 안 구분된다.
    #   시트를 눈으로 읽었을 때 バ행/パ행, ば행/ぱ행을 정반대로 적었었다.
    #   실측 빈도가 결정적이었다: 그 표로 세니 ば행 합계 27회 vs ぱ행 502회로
    #   일본어에서 있을 수 없는 비율이 나왔다(정정 후 ば행 502 / ぱ행 27).
    #   교차 검증 = 「ジューバ」「ゾアハーベスト」「すれば」「つぼ」가 전부 맞아떨어진다.
    "デドパピプペポバビブベボがぎぐげ",
    "ござじずぜぞだぢづでどぱぴぷぺぽ",
    "ばびぶべぼぁぃぅぇぉゃゅょっAB",
    "CDEFGHIJKLMNOPQR",
    "STUVWXYZ％威覚機技却究極",
    "型形撃御攻更国示銃準心性生素装体",
    "態着帝動売備標表物変防無力※",
]

# 1글리프 = 1글자가 아닌 자리 (합자 글리프)
LIGATURE = {0xFD: 'BP', 0xFE: 'EXP'}


def _build():
    t = []
    for r in ROWS:
        t.extend(list(r))
    assert len(t) == 256, '표가 256자가 아니다: %d' % len(t)
    for k, v in LIGATURE.items():
        t[k] = v
    t[1] = ' '
    return t


TABLE = _build()


# 번역문에서도 «기본 폰트의 원래 글리프»를 그대로 쓰는 글자들.
# (숫자·괄호·말줄임·느낌표 등은 한글 번역문에도 그대로 나온다)
REVERSE_KEEP = {}


def _build_keep():
    for i, c in enumerate(TABLE):
        if len(c) == 1 and (c in '0123456789'
                            or c in 'ABCDEFGHIJKLMNOPQRSTUVWXYZ'
                            or c in '…()『』！？ー＋。「」、・％×／=※　 '):
            REVERSE_KEEP.setdefault(c, i)


_build_keep()


def ch(idx):
    """글리프 index → 표시 문자열. 256 이상은 장면 FNT라 자리표시자를 준다."""
    if idx < 256:
        return TABLE[idx]
    return '【%d】' % (idx - 256)
