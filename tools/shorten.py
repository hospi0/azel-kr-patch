TOK = re.compile(r'<!([0-9A-Fa-f]{2})>|<([0-9A-Fa-f]{2})>|\\n|(.)', re.S)
NL = chr(92) + 'n'


def cells(s):
    return max(sum(1 for m in TOK.finditer(x) if m.group(3) is not None)
               for x in s.split(NL))


def shorten(s):
    for a, b in RULES:
        if a != b:
            s = s.replace(a, b)
    return s


def main():
    apply = '--apply' in sys.argv
    krdir = 'work/trans/kr'
    n = 0
    for fn in sorted(os.listdir(krdir)):
        if not fn.endswith('.tsv'):
            continue
        p = os.path.join(krdir, fn)
        lines = io.open(p, encoding='utf-8').read().split('\n')
        out = []
        for i, l in enumerate(lines):
            if i == 0 or not l:
                out.append(l)
                continue
            r = l.split('\t')
            if len(r) >= 7 and r[6] and r[6] != r[5]:
                s = shorten(r[6])
                if s != r[6]:
                    n += 1
                    r[6] = s
            out.append('\t'.join(r))
        if apply:
            io.open(p, 'w', encoding='utf-8', newline='').write('\n'.join(out))
    print('%s %d행' % ('축약 적용' if apply else '축약 대상(미적용)', n))


if __name__ == '__main__':
    main()
